#!/usr/bin/env python3
"""The repo invariants that are plain file checks, without compiling anything.

Reproduces two core tests so a leaf can run them in well under a second instead of a cargo build:

  * `the_module_map_matches_the_files_on_disk` (core/tests/module_map.rs): every `.rs` file under
    `core/src` (bare) and `core/crates/<name>/src` (prefixed `crates/<name>/src/`) has a row in the
    `## Module map` section of `core/MODULE_MAP.md`, and every row names a file that exists.
  * `no_core_file_holds_more_code_than_its_ceiling` (core/tests/file_size.rs): production code per
    file stays under LIMIT lines, or under its ceiling in `core/file-size-baseline.txt`.

The Rust tests stay the authority; this is their mirror. If the two disagree, fix this script.

Run from the repo root:  python scripts/check_invariants.py
Exit 0 = OK. Exit 1 = one line per violation, each ending with the fix.
"""

import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
LIMIT = 1000  # `LIMIT` in core/tests/file_size.rs
GENERATED_FILE = "src/route_index/generated.rs"
GENERATED_HEADER = "//! Generated by `python scripts/route_index_gate.py"


def source_dirs(core):
    """`(prefix, dir)` for core/src and every core/crates/<name>/src, as the Rust scans do."""
    dirs = [("", core / "src")]
    crates = core / "crates"
    if crates.is_dir():
        for entry in sorted(crates.iterdir(), key=lambda p: p.name):
            if (entry / "src").is_dir():
                dirs.append((f"crates/{entry.name}/src/", entry / "src"))
    return dirs


def rust_files(directory):
    """Every `.rs` file under `directory` at any depth: `(path from directory with /, Path)`."""
    return sorted(
        (path.relative_to(directory).as_posix(), path)
        for path in directory.rglob("*.rs")
        if path.is_file()
    )


def mapped_files(text):
    """The `.rs` rows of the `## Module map` section only (a row elsewhere cannot vouch)."""
    found = set()
    in_map = False
    for line in text.split("\n"):
        line = line.rstrip("\r")
        if line.startswith("## "):
            in_map = line[3:].startswith("Module map")
        if not in_map or not line.startswith("| `"):
            continue
        field, sep, _ = line[3:].partition("` |")
        if sep and field.endswith(".rs"):
            found.add(field)
    return found


def module_map_problems(core):
    map_path = core / "MODULE_MAP.md"
    if not map_path.is_file():
        return [f"{map_path} is missing: restore core/MODULE_MAP.md from git"]
    mapped = mapped_files(map_path.read_text(encoding="utf-8", errors="replace"))
    on_disk = {
        prefix + name for prefix, directory in source_dirs(core) for name, _ in rust_files(directory)
    }
    problems = []
    for name in sorted(on_disk - mapped):
        where = name if name.startswith("crates/") else f"src/{name}"
        problems.append(
            f"core/{where} has no row in core/MODULE_MAP.md: add a row "
            f"`| `{name}` | what it is responsible for |`"
        )
    for name in sorted(mapped - on_disk):
        problems.append(
            f"core/MODULE_MAP.md has a row for `{name}` and no such file exists: remove or fix the row "
            "(a moved file keeps its row under its new path)"
        )
    return problems


def opens_module(line):
    """`mod x`, `pub mod x`, `pub(crate) mod x`."""
    rest = line.lstrip()
    if rest.startswith("pub"):
        after = rest[3:]
        if after.startswith("("):
            _, sep, tail = after[1:].partition(") ")
            rest = tail if sep else ""
        else:
            rest = after.lstrip()
    return rest.startswith("mod ")


def declares_module(text):
    """A module that lives in its own file: `pub mod batch;`."""
    return opens_module(text) and text.endswith(";") and "{" not in text


def code_lines(source):
    """Production code lines, mirroring `code_lines` in core/tests/file_size.rs."""
    lines = source.split("\n")
    if lines and lines[-1] == "":
        lines.pop()  # Rust's `str::lines` has no empty last item
    count = 0
    in_block = False
    in_tests = None  # indentation of the inline test module being skipped
    for at, raw in enumerate(lines):
        line = raw.rstrip("\r")
        nxt = lines[at + 1] if at + 1 < len(lines) else None
        if in_tests is not None:
            if line.strip() == "}" and len(line) - len(line.lstrip()) == in_tests:
                in_tests = None
            continue
        opens_tests = nxt is not None and opens_module(nxt) and not declares_module(nxt.strip())
        if line.strip() == "#[cfg(test)]" and opens_tests:
            in_tests = len(line) - len(line.lstrip())
            continue
        text = line.strip()
        if in_block:
            in_block = "*/" not in text
            continue
        gates_a_declaration = (
            text.startswith("#[") and nxt is not None and declares_module(nxt.strip())
        )
        if not text or text.startswith("//") or declares_module(text) or gates_a_declaration:
            continue
        if text.startswith("/*"):
            in_block = "*/" not in text
            continue
        count += 1
    return count


def baseline(text):
    """`{path: ceiling}` from file-size-baseline.txt."""
    ceilings = {}
    for line in text.split("\n"):
        line = line.strip()
        if not line or line.startswith("#"):
            continue
        path, _, ceiling = line.rpartition(" ")
        if not path or not ceiling.isdigit():
            raise SystemExit(f"core/file-size-baseline.txt: bad line (need `<path> <ceiling>`): {line}")
        ceilings[path.strip()] = int(ceiling)
    return ceilings


def size_problems_for(counts, ceilings):
    found = []
    for path, lines in sorted(counts.items()):
        ceiling = ceilings.get(path)
        if ceiling is not None and lines > ceiling:
            found.append(
                f"core/{path}: {lines} lines of code, past its ceiling of {ceiling}: split the file "
                "by what it does (not into numbered parts)"
            )
        elif ceiling is None and lines > LIMIT:
            found.append(
                f"core/{path}: {lines} lines of code, past the limit of {LIMIT}: split the file by "
                "what it does (not into numbered parts)"
            )
    for path, ceiling in sorted(ceilings.items()):
        lines = counts.get(path)
        if lines is None:
            found.append(
                f"{path} is in core/file-size-baseline.txt and is not on disk: remove its line "
                "(a moved file takes its ceiling with it, under its new path)"
            )
        elif lines <= LIMIT:
            found.append(
                f"{path} is down to {lines} lines: remove its line from core/file-size-baseline.txt"
            )
        elif ceiling <= LIMIT:
            found.append(
                f"{path} has a ceiling of {ceiling}, at or under the limit: remove its line from "
                "core/file-size-baseline.txt"
            )
    return found


def file_size_problems(core):
    counts = {}
    for _, directory in source_dirs(core):
        for _, path in rust_files(directory):
            name = path.relative_to(core).as_posix()
            source = path.read_text(encoding="utf-8", errors="replace")
            if name.endswith(GENERATED_FILE) and source.startswith(GENERATED_HEADER):
                continue
            counts[name] = code_lines(source)
    if len(counts) <= 100:
        return [f"the scan found only {len(counts)} source files under {core}: is this the repo root?"]
    base = core / "file-size-baseline.txt"
    if not base.is_file():
        return [f"{base} is missing: restore core/file-size-baseline.txt from git"]
    return size_problems_for(counts, baseline(base.read_text(encoding="utf-8", errors="replace")))


def main(root=ROOT):
    core = Path(root) / "core"
    problems = module_map_problems(core) + file_size_problems(core)
    for problem in problems:
        print(problem)
    return 1 if problems else 0


if __name__ == "__main__":
    sys.exit(main())

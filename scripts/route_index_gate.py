#!/usr/bin/env python3
"""Route index freshness gate: scans core/src for axum routes and keeps
core/src/route_index/generated.rs in sync.

Usage:
  python scripts/route_index_gate.py              check (exit 0 fresh, 1 stale)
  python scripts/route_index_gate.py --write      regenerate core/src/route_index/generated.rs
  python scripts/route_index_gate.py --self-test  run synthetic cases (no repo files)
"""
import re
import sys
from pathlib import Path

GENERATED = "core/src/route_index/generated.rs"
SRC = "core/src"

# Routes that must exist but whose purpose is curated in hot.rs, not derived.
EXEMPT = [
    ("GET", "/routes/search"),
    ("POST", "/runs"),
    ("POST", "/jobs"),
    ("POST", "/runs/{id}/message"),
    ("GET", "/runs"),
    ("POST", "/proposals/{id}/approve"),
    ("POST", "/runs/{id}/cancel"),
]

METHODS = ("get", "post", "put", "delete", "patch")
HEADER = "//! Generated by `python scripts/route_index_gate.py --write`; do not edit by hand.\n"

_VIS = r"(?:pub(?:\([^)]*\))?\s+)?"
# An inline `#[cfg(test)] mod x {` block: everything from here on is test code.
_CFG_TEST_BLOCK = re.compile(r"#\[cfg\(test\)\]\s*" + _VIS + r"mod\s+\w+\s*\{")
# A `#[cfg(test)] mod x;` declaration: the file x.rs is test code.
_CFG_TEST_DECL = re.compile(r"#\[cfg\(test\)\]\s*" + _VIS + r"mod\s+(\w+)\s*;")


# ---- lexical helpers ------------------------------------------------------

def _blank(s):
    return re.sub(r"[^\n]", " ", s)


def _skip_string(text, i):
    """text[i] is '"'; return the index just past the closing quote."""
    i += 1
    while i < len(text):
        if text[i] == "\\":
            i += 2
            continue
        if text[i] == '"':
            return i + 1
        i += 1
    return i


def _raw_hashes(text, i):
    """If a raw string starts at text[i] ('r', #*, '"'), return its hash count."""
    if text[i] != "r" or (i > 0 and (text[i - 1].isalnum() or text[i - 1] == "_")):
        return None
    j = i + 1
    while j < len(text) and text[j] == "#":
        j += 1
    if j < len(text) and text[j] == '"':
        return j - i - 1
    return None


def _group(text, open_idx):
    """text[open_idx] == '('. Return (end_idx, masked_inner): end_idx is the index
    of the matching ')', masked_inner the inner text with strings, comments and
    everything nested three or more parens deep blanked out (newlines kept), so
    `get(handler)` calls and their first argument stay visible."""
    depth = 0
    i = open_idx
    out = []
    n = len(text)
    while i < n:
        c = text[i]
        if c == "/" and text.startswith("//", i):
            j = text.find("\n", i)
            j = n if j < 0 else j
            out.append(" " * (j - i))
            i = j
            continue
        h = _raw_hashes(text, i) if c == "r" else None
        if h is not None:
            close = '"' + "#" * h
            j = text.find(close, i + h + 2)
            j = n if j < 0 else j + len(close)
            out.append(_blank(text[i:j]))
            i = j
            continue
        if c == '"':
            j = _skip_string(text, i)
            out.append(_blank(text[i:j]))
            i = j
            continue
        if c == "(":
            depth += 1
            out.append(c if depth <= 2 else " ")
        elif c == ")":
            if depth == 1:
                return i, "".join(out)[1:]
            out.append(c if depth <= 2 else " ")
            depth -= 1
        else:
            out.append(c if depth <= 2 or c == "\n" else " ")
        i += 1
    return n, "".join(out)[1:]


def _cut_tests(text):
    m = _CFG_TEST_BLOCK.search(text)
    return text[: m.start()] if m else text


# ---- scanner --------------------------------------------------------------

def _fn_match(text, name):
    return re.search(
        r"^[ \t]*" + _VIS + r"(?:async\s+)?(?:unsafe\s+)?fn\s+" + re.escape(name) + r"\b",
        text,
        re.M,
    )


def _fn_args(text, m):
    """Parameter-list text of the fn matched by m."""
    i = m.end()
    if i < len(text) and text[i] == "<":  # generics
        depth = 0
        while i < len(text):
            if text[i] == "<":
                depth += 1
            elif text[i] == ">":
                depth -= 1
                if depth == 0:
                    i += 1
                    break
            i += 1
    j = text.find("(", i)
    if j < 0:
        return ""
    end, _ = _group(text, j)
    return text[j + 1 : end]


def _first_sentence(s):
    s = " ".join(s.split())
    m = re.search(r"[.!?](?:\s|$)", s)
    if m:
        s = s[: m.start() + 1]
    return s


def _doc_of_fn(text, m):
    """First sentence of the `///` doc above the fn matched by m, or None."""
    lines = text[: m.start()].split("\n")
    docs = []
    k = len(lines) - 1
    while k >= 0:
        ln = lines[k].strip()
        if ln.startswith("///"):
            docs.append(ln[3:].strip())
        elif ln.startswith("#["):
            pass
        else:
            break
        k -= 1
    if not docs:
        return None
    return _first_sentence(" ".join(reversed(docs))) or None


def _comment_above(text, pos):
    """The `//` block (not `///` or `//!`) directly above the line containing pos."""
    start = text.rfind("\n", 0, pos) + 1
    lines = text[:start].split("\n")[:-1]
    block = []
    k = len(lines) - 1
    while k >= 0:
        ln = lines[k].strip()
        if ln.startswith("//") and not ln.startswith("///") and not ln.startswith("//!"):
            block.append(ln[2:].strip())
            k -= 1
            continue
        break
    if not block:
        return None
    return _first_sentence(" ".join(reversed(block))) or None


def _humanise(handler):
    words = handler.replace("_", " ").strip()
    if not words:
        return "Route."
    return words[0].upper() + words[1:] + "."


def _find_type(text, name):
    """Locate `struct/enum name` (any indentation). Returns a dict or None."""
    m = re.search(
        r"^([ \t]*)(pub(?:\([^)]*\))?\s+)?(struct|enum)\s+" + re.escape(name) + r"\b(<?)",
        text,
        re.M,
    )
    if not m:
        return None
    pieces = re.split(r"(?<=[;}])[ \t]*\n", text[: m.start()])
    chunk = pieces[-1] if pieces else ""
    derive = False
    for d in re.finditer(r"#\[derive\(([^\]]*)\)\]", chunk, re.S):
        if re.search(r"\bJsonSchema\b", d.group(1)):
            derive = True
    return {
        "derive": derive,
        "vis": (m.group(2) or "").strip(),
        "indent": m.group(1),
        "generic": m.group(4) == "<",
    }


def scan_source(text, others=(), relpath=""):
    """Return a list of entry dicts {method, path, purpose, body, handler}
    from one Rust source string (ignoring everything after #[cfg(test)]).

    others: optional [(relpath, text)] searched when a handler or request type
    is not defined in this file. The extra type_* keys feed scan_repo's
    nameability pass."""
    text = _cut_tests(text)
    entries = []
    for rm in re.finditer(r"\.route\(", text):
        line_start = text.rfind("\n", 0, rm.start()) + 1
        if "//" in text[line_start : rm.start()]:
            continue  # commented out
        open_idx = rm.end() - 1
        end, masked = _group(text, open_idx)
        inner = text[open_idx + 1 : end]
        pm = re.match(r'\s*"((?:[^"\\]|\\.)*)"', inner)
        if not pm:
            continue
        path = pm.group(1)
        rest = masked[pm.end():]
        comment = _comment_above(text, rm.start())
        for cm in re.finditer(
            r"\b(" + "|".join(METHODS) + r")\s*\(\s*(\||[A-Za-z_][\w:]*)", rest
        ):
            raw = cm.group(2)
            handler = "closure" if raw == "|" else raw.split("::")[-1]
            entries.append(
                _entry(text, others, relpath, cm.group(1).upper(), path, handler, comment)
            )
    return entries


def _entry(text, others, relpath, method, path, handler, comment):
    body = ("none", None)
    purpose = None
    extra = {}
    sources = [(relpath, text)] + [(r, _cut_tests(t)) for r, t in others if r != relpath]
    if handler != "closure":
        for _src_path, src in sources:
            fm = _fn_match(src, handler)
            if not fm:
                continue
            purpose = _doc_of_fn(src, fm)
            jm = re.search(r"\bJson\s*<\s*([A-Za-z_][\w:]*)", _fn_args(src, fm))
            if jm:
                tname = jm.group(1).split("::")[-1]
                info = None
                for t_path, t_src in sources:
                    info = _find_type(t_src, tname)
                    if info:
                        extra = {
                            "type_file": t_path,
                            "type_vis": info["vis"],
                            "type_indent": info["indent"],
                            "type_generic": info["generic"],
                        }
                        break
                body = ("schema" if info and info["derive"] else "shapeless", tname)
            break
    if not purpose:
        purpose = comment or (
            _humanise(handler) if handler != "closure" else "Route " + path + "."
        )
    e = {
        "method": method,
        "path": path,
        "purpose": purpose,
        "body": body,
        "handler": handler,
    }
    e.update(extra)
    return e


def _is_test_file(rel, test_mods):
    p = Path(rel)
    return (
        rel in test_mods
        or p.stem == "tests"
        or p.stem.endswith("_tests")
        or "tests" in p.parts[:-1]
        or p.name == "generated.rs"
    )


def _module_parts(rel):
    parts = list(Path(rel).with_suffix("").parts)
    if parts[:2] == ["core", "src"]:
        parts = parts[2:]
    if parts and parts[-1] == "mod":
        parts.pop()
    if parts in (["lib"], ["main"]):
        parts = []
    return parts


def _mod_visible(files, parts):
    """True when every module on the path is declared pub/pub(crate) in its parent."""
    for k in range(1, len(parts) + 1):
        parent = parts[: k - 1]
        name = parts[k - 1]
        if parent:
            joined = "/".join(parent)
            cands = [f"{SRC}/{joined}.rs", f"{SRC}/{joined}/mod.rs"]
        else:
            cands = [f"{SRC}/lib.rs"]
        ok = False
        for c in cands:
            txt = files.get(c)
            if txt is None:
                continue
            m = re.search(
                r"^[ \t]*(pub(?:\([^)]*\))?\s+)?mod\s+" + re.escape(name) + r"\s*;",
                txt,
                re.M,
            )
            if m:
                ok = (m.group(1) or "").strip() in ("pub", "pub(crate)")
                break
        if not ok:
            return False
    return True


def _read_files(root):
    files = {}
    for p in sorted((Path(root) / SRC).rglob("*.rs")):
        files[p.relative_to(root).as_posix()] = p.read_text(encoding="utf-8")
    return files


def scan_repo(root):
    """Scan core/src/**/*.rs under root and return all entries."""
    files = _read_files(root)
    test_mods = set()
    for rel, txt in files.items():
        d = Path(rel)
        stemdir = d.parent if d.stem in ("mod", "lib", "main") else d.parent / d.stem
        for m in _CFG_TEST_DECL.finditer(txt):
            test_mods.add((stemdir / f"{m.group(1)}.rs").as_posix())
            test_mods.add((stemdir / m.group(1) / "mod.rs").as_posix())
    live = {r: t for r, t in files.items() if not _is_test_file(r, test_mods)}
    others = list(live.items())
    seen = {}
    for rel, txt in live.items():
        for e in scan_source(txt, others, rel):
            seen.setdefault((e["path"], e["method"]), e)
    entries = [seen[k] for k in sorted(seen)]
    _finish_bodies(entries, files)
    return entries


def _finish_bodies(entries, files):
    """Degrade schema bodies whose type is not nameable from route_index to
    shapeless, and attach the Rust path of the ones that are."""
    named = {}
    for e in entries:
        kind, tname = e["body"]
        if kind != "schema":
            continue
        tf = e.get("type_file")
        ok = (
            tf
            and e.get("type_vis") in ("pub", "pub(crate)")
            and not e.get("type_indent")
            and not e.get("type_generic")
            and _mod_visible(files, _module_parts(tf))
        )
        if not ok:
            e["body"] = ("shapeless", tname)
            continue
        rust = "::".join(["crate"] + _module_parts(tf) + [tname])
        e["rust_path"] = rust
        named.setdefault(tname, set()).add(rust)
    for e in entries:
        kind, tname = e["body"]
        if kind == "schema" and len(named.get(tname, ())) > 1:
            e["body"] = ("shapeless", tname)  # same name, different types
            e.pop("rust_path", None)


# ---- emitter / parser -----------------------------------------------------

def _rs(s):
    return s.replace("\\", "\\\\").replace('"', '\\"')


def _unrs(s):
    return re.sub(r"\\(.)", r"\1", s)


def _body_rs(body):
    kind, name = body
    if kind == "none":
        return "Body::None"
    if kind == "schema":
        return f'Body::Schema("{_rs(name)}")'
    return f'Body::Shapeless("{_rs(name)}")'


def emit(entries):
    """Render the deterministic generated.rs text (sorted by path, method)."""
    ordered = sorted(entries, key=lambda e: (e["path"], e["method"]))
    out = [HEADER, "\n", "use super::{Body, RouteEntry};\n", "\n"]
    out.append("pub const ROUTES: &[RouteEntry] = &[\n")
    for e in ordered:
        out.append("    RouteEntry {\n")
        out.append(f'        method: "{_rs(e["method"])}",\n')
        out.append(f'        path: "{_rs(e["path"])}",\n')
        out.append(f'        purpose: "{_rs(e["purpose"])}",\n')
        out.append(f"        body: {_body_rs(e['body'])},\n")
        out.append(f'        handler: "{_rs(e["handler"])}",\n')
        out.append("    },\n")
    out.append("];\n\n")
    out.append("fn schema<T: schemars::JsonSchema>() -> Option<serde_json::Value> {\n")
    out.append("    serde_json::to_value(schemars::schema_for!(T)).ok()\n")
    out.append("}\n\n")
    out.append(
        "/// JSON schema of a request type by name; `None` for types without a `JsonSchema` derive.\n"
    )
    out.append("pub fn schema_of(type_name: &str) -> Option<serde_json::Value> {\n")
    out.append("    match type_name {\n")
    arms = {}
    for e in ordered:
        if e["body"][0] == "schema" and e.get("rust_path"):
            arms[e["body"][1]] = e["rust_path"]
    for name in sorted(arms):
        line = f'        "{_rs(name)}" => schema::<{arms[name]}>(),'
        if len(line) > 100:
            out.append(f'        "{_rs(name)}" => {{\n')
            out.append(f"            schema::<{arms[name]}>()\n")
            out.append("        }\n")
        else:
            out.append(line + "\n")
    out.append("        _ => None,\n")
    out.append("    }\n")
    out.append("}\n")
    return "".join(out)


_STR = r'"((?:[^"\\]|\\.)*)"'
_ENTRY_RE = re.compile(
    r"method:\s*" + _STR + r",\s*path:\s*" + _STR + r",\s*purpose:\s*" + _STR + r",\s*"
    r'body:\s*Body::(None|Schema\("(?:[^"\\]|\\.)*"\)|Shapeless\("(?:[^"\\]|\\.)*"\)),\s*'
    r"handler:\s*" + _STR,
    re.S,
)


def parse_generated(text):
    """Parse the ROUTES entries back out of committed generated.rs text."""
    entries = []
    for m in _ENTRY_RE.finditer(text):
        b = m.group(4)
        if b == "None":
            body = ("none", None)
        else:
            kind, rest = b.split("(", 1)
            body = (kind.lower(), _unrs(rest[1:-2]))
        entries.append(
            {
                "method": _unrs(m.group(1)),
                "path": _unrs(m.group(2)),
                "purpose": _unrs(m.group(3)),
                "body": body,
                "handler": _unrs(m.group(5)),
            }
        )
    return entries


# ---- diff / commands ------------------------------------------------------

def diff(scanned, committed_text, exempt=EXEMPT):
    """Return (problems, ok). problems is a list of human-readable strings:
    'route without entry: ...', 'entry without route: ...', text drift,
    and exemptions that are not real routes."""
    problems = []
    s_keys = {(e["method"], e["path"]) for e in scanned}
    c_keys = {(e["method"], e["path"]) for e in parse_generated(committed_text)}
    for m, p in sorted(s_keys - c_keys, key=lambda k: (k[1], k[0])):
        problems.append(f"route without entry: {m} {p}")
    for m, p in sorted(c_keys - s_keys, key=lambda k: (k[1], k[0])):
        problems.append(f"entry without route: {m} {p}")
    for m, p in exempt:
        if (m, p) not in s_keys:
            problems.append(f"exemption is not a route: {m} {p}")
        elif (m, p) not in c_keys:
            problems.append(f"exempt route without entry: {m} {p}")
    if emit(scanned) != committed_text:
        problems.append(
            "generated.rs differs from the regenerated text; "
            "run: python scripts/route_index_gate.py --write"
        )
    return (problems, not problems)


def write(root):
    text = emit(scan_repo(root))
    with open(Path(root) / GENERATED, "w", encoding="utf-8", newline="\n") as f:
        f.write(text)
    return 0


def check(root):
    scanned = scan_repo(root)
    with open(Path(root) / GENERATED, encoding="utf-8", newline="") as f:
        committed = f.read()
    problems, ok = diff(scanned, committed)
    for p in problems:
        print(p)
    if ok:
        print(f"route index fresh ({len(scanned)} routes)")
    return 0 if ok else 1


# ---- self-test (written first) ------------------------------------------

def _keys(entries):
    return sorted((e["method"], e["path"]) for e in entries)


def _s1():
    src = 'fn r() { Router::new().route("/a", get(ha).post(hb)) }'
    assert _keys(scan_source(src)) == [("GET", "/a"), ("POST", "/a")]


def _s2():
    src = 'Router::new()\n    .route(\n        "/x",\n        post(h),\n    )\n'
    assert _keys(scan_source(src)) == [("POST", "/x")]


def _s3():
    src = (
        '.route("/real", get(h))\n'
        "#[cfg(test)]\nmod tests {\n"
        '    .route("/fake", get(h))\n}\n'
    )
    assert _keys(scan_source(src)) == [("GET", "/real")]


def _s4():
    src = (
        "#[derive(Deserialize, JsonSchema)]\nstruct WithDerive { a: u8 }\n"
        "#[derive(Deserialize)]\nstruct NoDerive { a: u8 }\n"
        "async fn h1(Json(b): Json<WithDerive>) {}\n"
        "async fn h2(Json(b): Json<NoDerive>) {}\n"
        "async fn h3() {}\n"
        '.route("/p1", post(h1))\n.route("/p2", post(h2))\n.route("/p3", post(h3))\n'
    )
    by = {e["path"]: e["body"] for e in scan_source(src)}
    assert by.get("/p1") == ("schema", "WithDerive"), by
    assert by.get("/p2") == ("shapeless", "NoDerive"), by
    assert by.get("/p3") == ("none", None), by


def _entries(*pairs):
    return [
        {"method": m, "path": p, "purpose": "x", "body": ("none", None), "handler": "h"}
        for m, p in pairs
    ]


def _s5():
    scanned = _entries(("GET", "/a"), ("GET", "/b"))
    committed = emit(_entries(("GET", "/a")))
    problems, ok = diff(scanned, committed, exempt=[])
    assert not ok and any("without entry" in p and "/b" in p for p in problems), problems


def _s6():
    scanned = _entries(("GET", "/a"))
    committed = emit(_entries(("GET", "/a"), ("GET", "/gone")))
    problems, ok = diff(scanned, committed, exempt=[])
    assert not ok and any("entry without route" in p and "/gone" in p for p in problems), problems


def _s7():
    scanned = _entries(("GET", "/a"), ("POST", "/b"))
    committed = emit(scanned)
    assert committed, "emit produced no text"
    problems, ok = diff(scanned, committed, exempt=[])
    assert ok and not problems, problems


def _s8():
    scanned = _entries(("GET", "/a"))
    committed = emit(scanned)
    problems, ok = diff(scanned, committed, exempt=[("GET", "/not-a-route")])
    assert not ok and any("/not-a-route" in p for p in problems), problems


def self_test():
    failed = []
    for name, fn in sorted((n, f) for n, f in globals().items()
                           if n.startswith("_s") and n[2:].isdigit()):
        try:
            fn()
            print(f"ok   {name[1:]}")
        except Exception as e:  # noqa: BLE001 - report any failure, never crash
            failed.append(name[1:])
            print(f"FAIL {name[1:]}: {type(e).__name__}: {e}")
    return 1 if failed else 0


def main(argv):
    root = str(Path(__file__).resolve().parent.parent)
    if "--self-test" in argv:
        return self_test()
    if "--write" in argv:
        return write(root) or 0
    return check(root)


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
